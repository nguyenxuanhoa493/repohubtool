_wrapped_title_cache = {}

def wrap_title_2lines(title, max_chars_per_line=16):
    key = (title, max_chars_per_line)
    if key in _wrapped_title_cache:
        return _wrapped_title_cache[key]

    title_clean = title.strip()
    if len(title_clean) <= max_chars_per_line:
        res = [title_clean]
    else:
        words = title_clean.split()
        line1 = ""
        line2 = ""

        for w in words:
            if not line1:
                line1 = w
            elif len(line1) + 1 + len(w) <= max_chars_per_line:
                line1 += " " + w
            else:
                if not line2:
                    line2 = w
                elif len(line2) + 1 + len(w) <= max_chars_per_line:
                    line2 += " " + w
                else:
                    line2 += " " + w

        if not line2:
            line1 = title_clean[:max_chars_per_line]
            line2 = title_clean[max_chars_per_line:]

        if len(line2) > max_chars_per_line:
            line2 = line2[:max_chars_per_line - 2] + ".."

        res = [line1, line2]

    if len(_wrapped_title_cache) > 400:
        _wrapped_title_cache.clear()
    _wrapped_title_cache[key] = res
    return res
